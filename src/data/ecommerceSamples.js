        mfgName: 'PepsiCo India Holdings Pvt. Ltd., Village Channo, Patiala 147201, Punjab',
        netQty: '52 g',
        mrp: '₹20.00 (incl. of all taxes)',
        unitSalePrice: '₹0.38 / 1 g',
        mfgDate: '05/2026',
        consumerCare: '1800 22 4020 | consumer.feedback@pepsico.com',
        countryOfOrigin: 'India',
        fssai: '10014064000435'
